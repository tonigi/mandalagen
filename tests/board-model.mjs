import assert from 'node:assert/strict';
import { createBoardFromNodes, createBoardModel } from '../board-model.js';
import { getColorableHexPaths, getFillValue } from '../svg-engine.js';
import { RANDOM_SYMMETRIES } from '../constants.js';
import { generatePattern } from '../pattern-engine.js';
import { createAppState } from '../app-state.js';
import { paths, measureNodes } from './helpers/template.mjs';

const cells = getColorableHexPaths({ querySelectorAll: () => paths });
const decoration = paths.find(path => path.getAttribute('id') === 'path2148');
const decorationFill = getFillValue(decoration);
const nodes = measureNodes(cells);
const board = createBoardFromNodes(nodes);
const snapshot = () => cells.map(getFillValue);
const original = snapshot();
for (const symmetry of RANDOM_SYMMETRIES) {
  const orbits = board.getOrbits(symmetry);
  assert.equal(orbits, board.getOrbits(symmetry), 'Reuse the cached group mapping');
  const orbit = [...orbits.values()].find(group => group.length === symmetry.order * (symmetry.mirror ? 2 : 1));
  board.beginStroke();
  board.paint(orbit[0], '#eb0000', symmetry);
  board.paint(orbit.at(-1), '#eb0000', symmetry);
  board.finishStroke();
  assert(orbit.every(path => getFillValue(path) === '#eb0000'));
  assert.equal(board.colorCounts().get('#eb0000'), orbit.length);
  board.undo();
  assert.deepEqual(snapshot(), original, 'One undo restores a whole symmetric gesture');
  board.redo();
  assert(orbit.every(path => getFillValue(path) === '#eb0000'));
  board.beginStroke();
  board.paint(orbit[0], '#ffffff', symmetry);
  board.finishStroke();
  assert(orbit.every(path => getFillValue(path) === '#ffffff'), 'Erase uses the same symmetry');
  board.undo();
  assert(orbit.every(path => getFillValue(path) === '#eb0000'));
  board.undo();
  assert.deepEqual(snapshot(), original);
  board.clearHistory();
}
board.clear();
assert.equal(board.colorCounts().get('#ffffff'), 1045);
board.undo();
assert.deepEqual(snapshot(), original);
assert.equal(getFillValue(decoration), decorationFill);
const state = createAppState();
const observed = [];
state.subscribe(value => observed.push(value));
state.set({ symmetry: 'c3', palette: 'blue', activeTab: 'draw' });
assert.equal(observed.at(-1).symmetry, 'c3');
assert.equal(observed.at(-1).palette, 'blue');
assert.equal(state.value.activeTab, 'draw');
const count = observed.length;
state.set({ symmetry: 'c3' });
assert.equal(observed.length, count, 'Unchanged controls do not cause update loops');
generatePattern(board, state.value);
assert(!board.canUndo && !board.canRedo, 'Replacing a design clears history');
const generated = snapshot();
generatePattern(board, state.value);
assert.deepEqual(snapshot(), generated, 'A seed reproduces the same design');
assert.equal(getFillValue(decoration), decorationFill);
// Measurements normalize screen geometry back into the SVG coordinate system.
const root = { querySelectorAll: () => paths, getBoundingClientRect: () => ({ left: 0, top: 0, width: 793.70135, height: 1122.52 }) };
const measured = createBoardModel(root, { width: 793.70135, height: 1122.52 });
assert.equal(measured.cells.length, 1045);
assert(Math.abs(measured.center.x - board.center.x) < 1e-8);
assert(!measured.canUndo && !measured.canRedo, 'New SVG has fresh history');
console.log('PASS: real-board symmetric paint/erase, gesture undo/redo, clear, history replacement, counts, cached groups, and shared state');
